#!/usr/bin/env python3
"""Regenerable extractor for the finished-goods material master: the "Code" tab of the client's
"Packing Traceability  FG Aging Report.xlsx" (docs/production). Writes
packages/contract/src/data/packingMaterials.ts — one row per sellable product: its description (the
"Grade" the packing sheet writes), its material code and its SKU (kg per pack: 20, or 22.68 for a
50 lbs pouch).

Why a master and not free text: every one of the 470 rows of the "Packing Traceability" tab carries a
material code from this list, with exactly this description and SKU (measured Nov 2026: 0 missing, 0
differing). So the app asks for the grade and reads the code and SKU from here, and a packed quantity in
kg is worked out as the sheet does (qty × SKU, which holds on 468 of its 470 rows).

Usage:  python tools/extract-packing-materials.py
"""
import json
import pathlib

import openpyxl

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "docs" / "production" / "Packing Traceability  FG Aging Report.xlsx"
OUT = ROOT / "packages" / "contract" / "src" / "data" / "packingMaterials.ts"


def main() -> None:
    wb = openpyxl.load_workbook(SRC, read_only=True, data_only=True)
    rows = []
    for r in wb["Code"].iter_rows(values_only=True):
        # The table starts in column D: Material Description, Material Code, SKU.
        desc, code, sku = r[3], r[4], r[5]
        if not desc or desc == "Material Description" or code is None:
            continue
        rows.append({"grade": str(desc).strip(), "code": str(int(code)), "sku": float(sku)})
    seen = set()
    for row in rows:
        if row["code"] in seen:
            raise SystemExit(f"Material code {row['code']} appears twice in the master")
        seen.add(row["code"])

    lines = [
        "// GENERATED by tools/extract-packing-materials.py from the \"Code\" tab of",
        "// docs/production/Packing Traceability  FG Aging Report.xlsx — do not hand-edit; re-run the tool.",
        "// The client's finished-goods master: what the packing sheet calls a Grade, its material code, and its",
        "// SKU (kg per pack). Every one of the sheet's 470 packing rows uses a code from this list, unchanged.",
        "",
        "export interface PackingMaterial {",
        "  grade: string;",
        "  code: string;",
        "  /** Kg in one pack: 20, or 22.68 for a 50 lbs pouch. */",
        "  sku: number;",
        "}",
        "",
        "export const PACKING_MATERIALS: PackingMaterial[] = [",
    ]
    for row in rows:
        sku = int(row["sku"]) if row["sku"].is_integer() else row["sku"]
        lines.append(f"  {{ grade: {json.dumps(row['grade'], ensure_ascii=False)}, code: \"{row['code']}\", sku: {sku} }},")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} materials -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
